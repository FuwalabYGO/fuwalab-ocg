import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(fileURLToPath(import.meta.url))
const v = JSON.parse(readFileSync(join(ROOT, 'vendor', 'versions.json'), 'utf8'))
const cs = v.repos.CardScripts
const cdb = v.repos.BabelCDB
if (!cs.commit || !cdb.commit) {
  console.warn('[ocg-release] commits manquants')
  process.exit(1)
}
const day = v.generatedAt.slice(0, 10)
const line = (n, r) => `- [${n}](${r.url}) : [\`${r.commit}\`](${r.url}/tree/${r.commit}) (${r.date})`
writeFileSync(join(ROOT, '..', 'notes.md'), `Card data for the FUWALAB automatic simulator, generated by \`ocg/sync.mjs\` on ${v.generatedAt}.

Sources (AGPL-3.0-or-later):

${line('CardScripts', cs)}
${line('BabelCDB', cdb)}
- Core: [${v.core.name}](${v.core.url}) ${v.core.version}, built from [ygopro-core](${v.core.core})
- [strings.conf](${v.strings.url})
`)
console.log(`tag=cards-${cs.commit.slice(0, 7)}-${cdb.commit.slice(0, 7)}`)
console.log(`title=Cartes ${day}`)
